#!/usr/bin/env python3
"""Generate src/rst/pygments_aliases.rs from Pygments' lexer mapping.

Regenerate with:

    PYTHONNOUSERSITE=1 uv run --locked --python 3.12 \
        --project tools/oracle_profiles/core python tools/gen_pygments_aliases.py
    cargo fmt --all

The `cargo fmt` is not optional: rustfmt repacks the emitted array, so
skipping it leaves a diff that is pure formatting.

`pygments.lexers.get_lexer_by_name(alias)` finds a builtin lexer when
`alias.lower()` is one of a lexer's aliases (`LEXERS` in
`pygments/lexers/_mapping.py`), then tries the plugin lexers, of which
the locked core profile has none. docutils' `Lexer` asks it for every
`code` language other than '' and 'text' (`docutils/utils/code_analyzer.py`)
and reports `No Pygments lexer found for "<language>".` when it finds none,
which is what the parse reads this table for.
"""

import pygments
from pygments.lexers._mapping import LEXERS
from pygments.plugin import find_plugin_lexers

EXPECTED_PYGMENTS = "2.21.0"

assert pygments.__version__ == EXPECTED_PYGMENTS, pygments.__version__
assert not list(find_plugin_lexers()), "plugin lexers would widen the table"

aliases = sorted({alias for _, _, names, _, _ in LEXERS.values() for alias in names})
assert all(alias == alias.lower() for alias in aliases)

with open("src/rst/pygments_aliases.rs", "w") as out:
    out.write(
        "//! GENERATED by tools/gen_pygments_aliases.py from Pygments %s\n"
        "//! (regen: `PYTHONNOUSERSITE=1 uv run --locked --python 3.12 \\\n"
        "//!     --project tools/oracle_profiles/core python tools/gen_pygments_aliases.py`).\n"
        "//! Do not edit by hand.\n\n" % pygments.__version__
    )
    out.write(
        "/// Every alias of a builtin Pygments lexer, sorted: the names\n"
        "/// `get_lexer_by_name` finds a lexer for, once lowercased.\n"
    )
    out.write("pub(crate) const LEXER_ALIASES: &[&str] = &[\n")
    for alias in aliases:
        out.write('    "%s",\n' % alias.replace("\\", "\\\\").replace('"', '\\"'))
    out.write("];\n")
